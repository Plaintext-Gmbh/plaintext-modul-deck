-- Karte 2162: Kanban-Board und Agenten-Kollaboration.
--
-- Drei Tabellen, mehr braucht das Geruest nicht:
--   deck_karte     die Karten des Boards (fuenf Stapel, Labels, Prioritaet, Rueckfrage-Markierung)
--   deck_kommentar Beitraege zu einer Karte; RUECKFRAGE und ANTWORT stehen mit den normalen
--                  Kommentaren in derselben Tabelle, weil das Panel sie chronologisch mischt
--   deck_nachricht Nachrichten zwischen Agenten (Chat und die Matrix "wer schreibt wie viel an wen")
--
-- Die Auditing-Spalten (deleted, created_by, mandat, tags ...) kommen aus SuperModel; jede Entity
-- dieses Moduls erbt davon. PostgreSQL, wie die gesamte App - kein HSQLDB-Zweig.
--
-- Bewusst KEINE Migration von Nextcloud-Deck-Daten: die Grenze der Karte sagt, dass das bestehende
-- Deck bleibt und ohne Wort von Daniel nicht umgezogen wird.

CREATE TABLE deck_karte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titel VARCHAR(300) NOT NULL,
    beschreibung TEXT,
    stapel VARCHAR(20) NOT NULL,
    prio INTEGER NOT NULL DEFAULT 0,
    labels VARCHAR(300),
    bearbeiter VARCHAR(100),
    rueckfrage BOOLEAN NOT NULL DEFAULT FALSE,
    interaktiv BOOLEAN NOT NULL DEFAULT FALSE,
    kurzfassung VARCHAR(300),
    deleted BOOLEAN DEFAULT FALSE,
    created_by VARCHAR(255),
    created_date TIMESTAMP,
    last_modified_by VARCHAR(255),
    last_modified_date TIMESTAMP,
    mandat VARCHAR(255),
    tags VARCHAR(2000)
);

-- board() liest je Mandat und gruppiert im Speicher nach Stapel; der Index deckt genau diese Abfrage.
CREATE INDEX idx_deck_karte_mandat ON deck_karte (mandat);

-- Das Rueckfrage-Panel ist eine Teilmenge davon und laeuft bei jedem Seitenaufbau.
CREATE INDEX idx_deck_karte_rueckfrage ON deck_karte (mandat, rueckfrage);

CREATE TABLE deck_kommentar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    karte_id BIGINT NOT NULL,
    autor VARCHAR(100) NOT NULL,
    art VARCHAR(20) NOT NULL DEFAULT 'KOMMENTAR',
    text TEXT NOT NULL,
    gelesen BOOLEAN NOT NULL DEFAULT FALSE,
    deleted BOOLEAN DEFAULT FALSE,
    created_by VARCHAR(255),
    created_date TIMESTAMP,
    last_modified_by VARCHAR(255),
    last_modified_date TIMESTAMP,
    mandat VARCHAR(255),
    tags VARCHAR(2000),
    CONSTRAINT fk_deck_kommentar_karte FOREIGN KEY (karte_id) REFERENCES deck_karte (id)
);

CREATE INDEX idx_deck_kommentar_karte ON deck_kommentar (karte_id);
CREATE INDEX idx_deck_kommentar_mandat ON deck_kommentar (mandat);

CREATE TABLE deck_nachricht (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    von VARCHAR(100) NOT NULL,
    an VARCHAR(100) NOT NULL,
    text TEXT NOT NULL,
    gelesen BOOLEAN NOT NULL DEFAULT FALSE,
    deleted BOOLEAN DEFAULT FALSE,
    created_by VARCHAR(255),
    created_date TIMESTAMP,
    last_modified_by VARCHAR(255),
    last_modified_date TIMESTAMP,
    mandat VARCHAR(255),
    tags VARCHAR(2000)
);

CREATE INDEX idx_deck_nachricht_mandat ON deck_nachricht (mandat);

-- "etwas fuer mich?" fragt nach ungelesenen Nachrichten eines Empfaengers.
CREATE INDEX idx_deck_nachricht_empfaenger ON deck_nachricht (mandat, an, gelesen);
